# check whether the approved DepEd enrollment releases publish an annex-to-mother link (#102).
#
# runs locally with no Databricks compute:
#   RAW_DATA_DIR=~/Projects/reached-hq/raw-data python analysis/cross_source/cross_source_deped_annex.py
#
# RAW_DATA_DIR must contain deped/original/ and the three approved enrollment archives.

import csv
import hashlib
import io
import os
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "docs" / "data" / "cross-source" / "generated" / "deped_annexes_without_mother.md"
FILES = {
    "2023-24": ("Enrollment-in-SY-2023-2024.zip", "a10f4d0f9082919c13b3a091774c8231c99c95b1b1872310714107013b77dbbb", "utf-8", "Annex/Extension School"),
    "2024-25": ("Enrollment-in-SY-2024-2025.zip", "fd5dd74a62b828608c62335b7c324ddf05be58e3f05465fee68854795f5b1a92", "utf-8", "Annex/Extension School"),
    "2025-26": ("Enrollment-in-SY-2025-2026.zip", "ab4d7e24b3a46a99db2c76dee5279a976e4c3a76062e79f7217e70dc6dd1b450", "cp1252", "Annex or Extension school(s)"),
}


def source_folder():
    raw = os.environ.get("RAW_DATA_DIR")
    if not raw:
        sys.exit("Set RAW_DATA_DIR to the folder that contains deped/original/.")
    root = Path(raw).expanduser()
    nested = root / "deped" / "original"
    return nested if nested.is_dir() else root


def read_rows(path, expected_sha, encoding):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != expected_sha:
        sys.exit(f"{path.name}: SHA-256 does not match the deped_enrollment source card. Stop and re-inventory.")
    with zipfile.ZipFile(path) as archive:
        members = [name for name in archive.namelist() if name.endswith(".csv")]
        if len(members) != 1:
            sys.exit(f"{path.name}: expected one CSV, found {len(members)}.")
        return list(csv.DictReader(io.StringIO(archive.read(members[0]).decode(encoding))))


def main():
    folder = source_folder()
    listed = []
    public_annexes = 0
    for year, (name, sha, encoding, annex_label) in FILES.items():
        rows = read_rows(folder / name, sha, encoding)
        columns = set(rows[0])
        link_columns = sorted(column for column in columns if "mother" in column.lower())
        annexes = [row for row in rows if row["annex_status"] == annex_label]
        year_public_annexes = sum(row["sector"] == "Public" for row in annexes)
        public_annexes += year_public_annexes
        print(f"[AN-1] SY {year}: checksum OK; mother-school columns {link_columns}; annexes {len(annexes):,}; public {year_public_annexes:,}")
        listed.extend((year, row["school_id"]) for row in annexes)

    lines = [
        "<!-- Generated by analysis/cross_source/cross_source_deped_annex.py; do not edit by hand. -->",
        "# DepEd annexes without a published mother-school link",
        "",
        "Every acquired enrollment release identifies annex schools but has no mother-school ID column.",
        "`mother_school_id` and `match_method` therefore remain blank; `evidence` records the checked source limitation.",
        f"The list contains {len(listed):,} annex-school years in total: {public_annexes:,} public records in scope for AP2 and AP3 and {len(listed) - public_annexes:,} non-public records retained for source completeness.",
        "",
        "| School year | Annex school ID | Mother school ID | Match method | Evidence |",
        "|---|---|---|---|---|",
    ]
    lines.extend(f"| {year} | {school_id} |  |  | deped_enrollment_annex_status_only |" for year, school_id in sorted(listed))
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[AN-2] listed {len(listed):,} unmatched annex-school years ({public_annexes:,} public) in {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
